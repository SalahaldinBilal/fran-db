use std::{
    error::Error,
    future::Future,
    panic::{self, AssertUnwindSafe},
    pin::Pin,
};

use fran_db_lib::db::session::{ContextId, DatabaseSession};
use fran_db_lib::db::types::{ResultSet, StatementOutcome};
use libtest_mimic::Failed;

use crate::servers::{Flavor, Server, Spec};

pub type TestResult<T = ()> = Result<T, Box<dyn Error>>;
pub type CaseFuture<'a> = Pin<Box<dyn Future<Output = TestResult> + 'a>>;

#[derive(Clone, Copy)]
pub struct Case {
    pub name: &'static str,
    pub only: Option<Flavor>,
    pub run: for<'a> fn(&'a Ctx) -> CaseFuture<'a>,
}

impl Case {
    pub fn applies_to(&self, spec: &Spec) -> bool {
        self.only.is_none_or(|flavor| flavor == spec.flavor)
    }
}

macro_rules! cases {
    ($only:expr; $($name:ident),* $(,)?) => {
        vec![$($crate::support::Case {
            name: stringify!($name),
            only: $only,
            run: |ctx| Box::pin($name(ctx)),
        }),*]
    };
}
pub(crate) use cases;

const MYSQL_SEED: &str = "
CREATE TABLE items (
  id INT NOT NULL AUTO_INCREMENT,
  name VARCHAR(40) NOT NULL,
  price DECIMAL(10,2) NULL,
  note TEXT NULL,
  PRIMARY KEY (id)
);
INSERT INTO items (name, price, note) VALUES ('apple', 1.50, 'red fruit'), ('banana', 0.25, NULL), ('cherry', 12.00, 'it''s small');
CREATE VIEW cheap_items AS SELECT id, name FROM items WHERE price < 2;
";

const POSTGRES_SEED: &str = "
CREATE TABLE items (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(40) NOT NULL,
  price numeric(10,2),
  note text,
  PRIMARY KEY (id)
);
INSERT INTO items (name, price, note) VALUES ('apple', 1.50, 'red fruit'), ('banana', 0.25, NULL), ('cherry', 12.00, 'it''s small');
CREATE VIEW cheap_items AS SELECT id, name FROM items WHERE price < 2;
";

/// A session working in its own seeded database (MySQL) or schema (Postgres) named `ns`.
pub struct Ctx {
    pub spec: &'static Spec,
    pub session: Box<dyn DatabaseSession>,
    pub ns: String,
    pub context: ContextId,
}

fn first_error(outcomes: &[StatementOutcome]) -> Option<String> {
    outcomes
        .iter()
        .find_map(|outcome| outcome.error.as_ref().map(|error| format!("{}\n  in: {}", error.message, outcome.sql)))
}

impl Ctx {
    async fn open(server: &Server) -> TestResult<Self> {
        let session = server.connect().await?;
        let ns = format!("e2e_{}", &uuid::Uuid::new_v4().simple().to_string()[..12]);
        let mut ctx = Self {
            spec: server.spec,
            session,
            ns,
            context: 0,
        };

        let create = ctx.pick(
            format!("CREATE DATABASE `{}`", ctx.ns),
            format!("CREATE SCHEMA \"{}\"", ctx.ns),
        );
        ctx.run_fresh(&create).await?;
        ctx.context = ctx.session.open_context(Some(ctx.ns.clone())).await?;
        ctx.run(ctx.pick(MYSQL_SEED, POSTGRES_SEED)).await?;
        Ok(ctx)
    }

    async fn close(self) {
        self.session.close_context(self.context).await;
        let drop = self.pick(
            format!("DROP DATABASE `{}`", self.ns),
            format!("DROP SCHEMA \"{}\" CASCADE", self.ns),
        );
        let _ = self.run_fresh(&drop).await;
        self.session.close().await;
    }

    pub fn flavor(&self) -> Flavor {
        self.spec.flavor
    }

    pub fn pick<T>(&self, mysql: T, postgres: T) -> T {
        match self.flavor() {
            Flavor::Mysql => mysql,
            Flavor::Postgres => postgres,
        }
    }

    /// Runs SQL in the test's query context and fails on the first statement error.
    pub async fn run(&self, sql: &str) -> TestResult<Vec<StatementOutcome>> {
        let outcomes = self.session.execute(self.context, sql, 1000).await?;
        match first_error(&outcomes) {
            Some(error) => Err(error.into()),
            None => Ok(outcomes),
        }
    }

    /// Runs SQL on a context of its own, opened without a default database or schema.
    pub async fn run_fresh(&self, sql: &str) -> TestResult<Vec<StatementOutcome>> {
        let context = self.session.open_context(None).await?;
        let outcomes = self.session.execute(context, sql, 1000).await;
        self.session.close_context(context).await;
        let outcomes = outcomes?;
        match first_error(&outcomes) {
            Some(error) => Err(error.into()),
            None => Ok(outcomes),
        }
    }

    /// The first result set of the last statement in `sql`.
    pub async fn query(&self, sql: &str) -> TestResult<ResultSet> {
        let outcomes = self.run(sql).await?;
        outcomes
            .last()
            .and_then(|outcome| outcome.result_sets.first().cloned())
            .ok_or_else(|| format!("no result set from: {sql}").into())
    }
}

pub fn values(set: &ResultSet, column: &str) -> Vec<Option<String>> {
    let index = set
        .columns
        .iter()
        .position(|meta| meta.name == column)
        .unwrap_or_else(|| panic!("no column {column} in the result"));
    set.rows.iter().map(|row| row[index].clone()).collect()
}

pub fn texts(set: &ResultSet, column: &str) -> Vec<String> {
    values(set, column).into_iter().map(|value| value.unwrap_or_default()).collect()
}

pub fn run_case(server: &Server, case: Case) -> Result<(), Failed> {
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .map_err(Failed::from)?;
    let ctx = runtime
        .block_on(Ctx::open(server))
        .map_err(|error| Failed::from(format!("setup failed: {error}")))?;

    let outcome = panic::catch_unwind(AssertUnwindSafe(|| runtime.block_on((case.run)(&ctx))));
    runtime.block_on(ctx.close());

    match outcome {
        Ok(result) => result.map_err(Failed::from),
        Err(payload) => panic::resume_unwind(payload),
    }
}
